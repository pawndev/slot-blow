fn glyph(ch: char) -> Option<&'static [&'static str; ROWS]> {
    GLYPHS.iter().find(|(c, _)| *c == ch).map(|(_, rows)| rows)
}

fn advance(ch: char) -> usize {
    match glyph(ch) {
        Some(rows) => rows.iter().map(|r| r.len()).max().unwrap_or(0) + 1,
        None => SPACE,
    }
}

pub fn knows(ch: char) -> bool {
    ch == ' ' || glyph(ch).is_some()
}

pub fn width(text: &str) -> usize {
    text.chars().map(advance).sum::<usize>().saturating_sub(1)
}

pub fn draw(text: &str, x: i32, y: i32, mut plot: impl FnMut(i32, i32)) {
    let mut pen = x;
    for ch in text.chars() {
        if let Some(rows) = glyph(ch) {
            for (dy, row) in rows.iter().enumerate() {
                for (dx, b) in row.bytes().enumerate() {
                    if b == b'#' {
                        plot(pen + dx as i32, y + dy as i32);
                    }
                }
            }
        }
        pen += advance(ch) as i32;
    }
}

pub fn wrap(text: &str, max_w: usize) -> Vec<String> {
    let mut lines = Vec::new();
    for para in text.split('\n') {
        let mut line = String::new();
        for word in para.split_whitespace() {
            let joined = match line.is_empty() {
                true => word.to_string(),
                false => format!("{line} {word}"),
            };
            if line.is_empty() || width(&joined) <= max_w {
                line = joined;
            } else {
                lines.push(std::mem::replace(&mut line, word.to_string()));
            }
        }
        lines.push(line);
    }
    lines
}
